import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {EventEmitter} from 'node:events';
import {PassThrough} from 'node:stream';
import {figmaUrl,framePath,makeTask} from '../studio/core.js';
import {createStudio} from '../studio/server.js';
const root=process.cwd();
test('Studio passes Figma URLs as one argument and never selects an existing page for draft writes',()=>{
 const url='https://www.figma.com/design/abc/Design?node-id=2-3&t=anything';
 assert.equal(new URL(figmaUrl(url)).search,'?node-id=2-3');
 assert.throws(()=>figmaUrl('https://evil.test/design/abc?node-id=2-3'));
 assert.throws(()=>framePath(root,'../secrets'));
 const build=makeTask(root,{action:'build',url,mode:'deterministic'},{});
 assert.ok(build.args.includes('--no-inject'));assert.ok(build.args.includes('--deterministic'));
 const draft=makeTask(root,{action:'draft',frame:'pgslot-thailand-com-84cdd226'},{});
 assert.ok(!draft.args.includes('--page'));assert.ok(draft.args.includes('--title'));
});
test('Studio requires a local session, rejects cross-origin mutations and serializes jobs',async t=>{
 const dir=fs.mkdtempSync(path.join(root,'.test-work/studio-'));fs.mkdirSync(path.join(dir,'output'));
 let child,launch;
 const studio=createStudio({workspace:dir,spawnImpl:(command,args,options)=>{launch={command,args,options};child=new EventEmitter();child.stdin=new PassThrough();child.stdout=new PassThrough();child.stderr=new PassThrough();return child;}});
 await new Promise(resolve=>studio.server.listen(0,'127.0.0.1',resolve));
 t.after(()=>new Promise(resolve=>studio.server.close(resolve)));
 const origin=`http://127.0.0.1:${studio.server.address().port}`;
 assert.equal((await fetch(origin+'/api/state')).status,401);
 const login=await fetch(origin+'/?token='+studio.token,{redirect:'manual'});assert.equal(login.status,303);
 const cookie=login.headers.get('set-cookie').split(';')[0];
 const post=(route,data,requestOrigin=origin)=>fetch(origin+route,{method:'POST',headers:{cookie,origin:requestOrigin,'content-type':'application/json'},body:JSON.stringify(data)});
 assert.equal((await post('/api/config',{FIGMA_TOKEN:'secret-fixture'},'https://evil.test')).status,403);
 assert.equal((await post('/api/config',{FIGMA_TOKEN:'secret-fixture'})).status,200);
 const task={action:'build',url:'https://www.figma.com/design/abc?node-id=2-3',mode:'deterministic'};
 assert.equal((await post('/api/jobs',task)).status,202);
 assert.equal(launch.options.shell,false);assert.equal(launch.options.windowsHide,true);
 assert.equal((await post('/api/jobs',task)).status,400);
 child.stdout.write('Token secret-fixture');child.emit('close',0);
 const state=await (await fetch(origin+'/api/state',{headers:{cookie}})).json();
 assert.equal(state.jobs[0].status,'completed');assert.equal(state.jobs[0].visualStatus,'Not verified');
 assert.ok(!JSON.stringify(state).includes('secret-fixture'));assert.match(state.jobs[0].log,/redacted/);
});
